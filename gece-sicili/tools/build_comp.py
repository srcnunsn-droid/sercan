#!/usr/bin/env python3
"""Write the HyperFrames root composition (index.html) for one episode.
HyperFrames allows exactly ONE root composition per project, so the orientation is chosen here:
   python3 tools/build_comp.py 01 v   -> index.html vertical   1080x1920 (Instagram/Reels master, default)
   python3 tools/build_comp.py 01 h   -> index.html horizontal 1920x1080 (landscape version; same story, own framing)"""
import sys, os
EP = sys.argv[1] if len(sys.argv) > 1 else "01"
ROOT = os.path.join(os.path.dirname(__file__), "..")
DUR = 120

FONTS = open(os.path.join(ROOT, "lib/fonts.css")).read().replace("../assets/", "assets/")
SCRIPTS = ["assets/vendor/gsap.min.js", "lib/core.js", "lib/constants.js", "lib/rig.js", "lib/human.js",
           "characters/idil.js", "characters/saren.js", "characters/tovan.js",
           "sets/props.js", "sets/morgue.js", "sets/morgue-inserts.js", "lib/player.js",
           f"data/ep-{EP}-voice.js", f"data/ep-{EP}.js"]

def page(W, H, sub_css):
    tags = "\n".join(f'    <script src="{s}"></script>' for s in SCRIPTS)
    return f"""<!doctype html>
<html lang="tr">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <!-- GENERATED by tools/build_comp.py — Gece Sicili, Bölüm {EP}. Edit data/ep-{EP}.js, not this file. -->
{tags}
    <style>
{FONTS}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: {W}px; height: {H}px; overflow: hidden; background: #0d1224; }}
      #root {{ position: relative; width: {W}px; height: {H}px; overflow: hidden; }}
      #stage {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
      #subs {{ position: absolute; text-align: center; font-family: GSSerif, serif; color: #fff; opacity: 0;
        text-shadow: -3px -3px 0 #120d16, 3px -3px 0 #120d16, -3px 3px 0 #120d16, 3px 3px 0 #120d16,
                     0 -3px 0 #120d16, 0 3px 0 #120d16, -3px 0 0 #120d16, 3px 0 0 #120d16, 0 6px 14px rgba(0,0,0,.75); }}
      #subs .tag {{ font-size: 0.6em; letter-spacing: 0.12em; color: #dff3f0; margin-bottom: 0.2em; }}
{sub_css}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <svg id="stage" class="clip" data-start="0" data-duration="{DUR}" data-track-index="0" data-layout-allow-overflow data-layout-ignore xmlns="http://www.w3.org/2000/svg"></svg>
      <div id="subs" data-layout-allow-caption-zone></div>
      <audio id="mix" class="clip" src="audio/mix/ep{EP}-mix.wav" data-start="0" data-duration="{DUR}" data-track-index="1" data-volume="1"></audio>
    </div>
    <script>
      (function () {{
        const P = GS.Player({{ ep: window.GS_EP, voice: window.GS_VOICE, W: {W}, H: {H},
          svg: document.getElementById("stage"), subs: document.getElementById("subs") }});
        window.__gs = P;
        const proxy = {{ t: 0 }};
        const tl = gsap.timeline({{ paused: true }});
        tl.to(proxy, {{ t: {DUR}, duration: {DUR}, ease: "none", onUpdate: () => P.render(proxy.t) }}, 0);
        P.render(0);
        window.__timelines = window.__timelines || {{}};
        window.__timelines["main"] = tl;
      }})();
    </script>
  </body>
</html>
"""

V_CSS = """      #subs { left: 60px; right: 60px; bottom: 420px; font-size: 47px; line-height: 1.25; }"""
H_CSS = """      #subs { left: 240px; right: 240px; bottom: 70px; font-size: 50px; line-height: 1.22; }"""
ORI = sys.argv[2] if len(sys.argv) > 2 else "v"
if ORI == "h":
    open(os.path.join(ROOT, "index.html"), "w").write(page(1920, 1080, H_CSS))
    print("wrote index.html HORIZONTAL 1920x1080 for episode", EP)
else:
    open(os.path.join(ROOT, "index.html"), "w").write(page(1080, 1920, V_CSS))
    print("wrote index.html VERTICAL 1080x1920 for episode", EP)
