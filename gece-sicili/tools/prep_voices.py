#!/usr/bin/env python3
"""Trim voice lines and measure them (CLAUDE.md §10.1: timing comes from the REAL audio).
For every audio/voice/epXX_lNN_<speaker>.wav:
  - trim leading/trailing silence to <= 0.08 s (keeps natural breaths inside the line)
  - write audio/voice/trim/epXX_lNN_<speaker>.wav (48 kHz mono)
  - amplitude envelope at 30 fps (0..1) for lip-flap
  - the longest inner pause (for splitting two-sentence lines into two subtitle cards)
Writes data/ep-XX-voice.js  (window.GS_VOICE = {...}).
Usage: python3 tools/prep_voices.py 01"""
import numpy as np, subprocess, glob, os, json, sys, re

EP = sys.argv[1] if len(sys.argv) > 1 else "01"
ROOT = os.path.join(os.path.dirname(__file__), "..")
SR = 48000
FPS = 30
PAD = 0.08


def load(f):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", f, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()


def rms_frames(x, hop):
    n = len(x) // hop
    return np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1) + 1e-12)


out = {}
os.makedirs(os.path.join(ROOT, "audio/voice/trim"), exist_ok=True)
for f in sorted(glob.glob(os.path.join(ROOT, f"audio/voice/ep{EP}_l*_*.wav"))):
    name = os.path.basename(f)[:-4]
    m = re.match(rf"ep{EP}_l(\d+)_(\w+)", name)
    ln, spk = int(m.group(1)), m.group(2)
    x = load(f)
    hop = SR // 100  # 10 ms
    r = rms_frames(x, hop)
    db = 20 * np.log10(r)
    thr = max(db.max() - 38, -50)
    on = np.where(db > thr)[0]
    s0 = max(0, on[0] * hop - int(PAD * SR))
    s1 = min(len(x), (on[-1] + 1) * hop + int(PAD * SR))
    y = x[s0:s1]
    # fade 5 ms at both ends to avoid clicks
    fl = int(0.005 * SR)
    y[:fl] *= np.linspace(0, 1, fl)
    y[-fl:] *= np.linspace(1, 0, fl)
    tp = os.path.join(ROOT, "audio/voice/trim", name + ".wav")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-", "-c:a", "pcm_s16le", tp], input=y.astype(np.float32).tobytes())
    dur = len(y) / SR
    # envelope @30fps, normalised to the line's own loud parts
    e = rms_frames(y, SR // FPS)
    e = e / (np.percentile(e, 95) + 1e-9)
    e = np.clip(e, 0, 1.3)
    # speech flags per 10 ms -> onset/offset of speech inside the trimmed file
    r2 = rms_frames(y, hop)
    sp = 20 * np.log10(r2) > thr
    idx = np.where(sp)[0]
    speech_on = idx[0] / 100 if len(idx) else 0
    speech_off = (idx[-1] + 1) / 100 if len(idx) else dur
    # longest inner pause (>= 0.15 s) for card split
    best = None
    run = 0
    for i in range(idx[0], idx[-1] + 1) if len(idx) else []:
        if not sp[i]:
            run += 1
        else:
            if run >= 15 and (best is None or run > best[1]):
                best = (i - run, run)
            run = 0
    split = round((best[0] + best[1] / 2) / 100, 3) if best else None
    out[ln] = {
        "line": ln, "speaker": spk, "file": f"audio/voice/trim/{name}.wav", "dur": round(dur, 3),
        "speechOn": round(speech_on, 3), "speechOff": round(speech_off, 3), "split": split,
        "env": [round(float(v), 2) for v in e],
    }
    print(f"l{ln:02d} {spk:6s} raw {len(x)/SR:5.2f}s -> trim {dur:5.2f}s  split {split}")

js = "// GENERATED by tools/prep_voices.py from the real voice files. Do not edit by hand.\nwindow.GS_VOICE = " + json.dumps(out, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, f"data/ep-{EP}-voice.js"), "w").write(js)
print("total speech", round(sum(v["dur"] for v in out.values()), 2), "s")
